w("# Option E: The Stepped Highlands. Generated by scratchpad/options/e/gen_e.py; render with")
w("# py -3.10 tools/world/plan.py render docs/design/world/options/e-stepped-highlands.yaml PLANDIR")
w("# Height is difficulty: coastal lowlands T1 (y 64-75), a 40-60 block escarpment up to the middle")
w("# plateau T2 (y ~115), a second escarpment to the high plateau T3 (y ~168), the summit T4 (y ~205)")
w("# cradling a frozen sky lake. Rivers cut gorges down through the escarpments to the sea.")
w("size: 32768")
w("seed: 5151")
w("coast_warp: 600")
w("region_warp: 380")
w("blend_px: 10")
w("shore_width: 700")
w("shelf_width: 1400")
w("")
w("coast: " + line(ring(R0, 4)))
w("")
w("islands:")
w("  - {circle: [14300, -9800, 900]}        # BoP Volcano island, northeast sea")
w("  - {circle: [-14100, -10600, 800]}      # vanilla Mushroom Island, northwest sea")
w("  - {ring: [10400, 14200, 1300, 780]}    # RWG Tropical Island atoll round a coral lagoon, south")
w("")
w("# The escarpments: nested table-lands, each a sheer wall. Order matters: lower tier first.")
w("plateaus:")
w(f"  - {{polygon: {line(ring(R2, 3))}, top: 115, wall: 55, top_relief: 9, relief: 55}}")
w(f"  - {{polygon: {line(ring(R3, 3))}, top: 166, wall: 50, top_relief: 10, relief: 60}}")
w(f"  - {{polygon: {line(ring(R4, 4))}, top: 204, wall: 38, top_relief: 6, relief: 40}}")
# Outlier buttes: lone T3 table mountains standing in the lowlands, in sight of each T1 spawn.
buttes = {  # angle: (biome, radius)
    170: (187, 420),  # W, Redwood coast: BoP Ominous Woods butte
    128: (78, 400),   # SW, cherry coast: BoP Dead Forest butte
    95: (187, 430),   # S, tropics: BoP Ominous Woods butte
    52: (251, 420),   # SE, mangrove: BoP Wasteland butte
    5: (77, 440),     # E, savanna: BoP Crag butte
}
for a, (b, r) in buttes.items():
    c = pt((R0(a) + R2(a)) / 2 + 300, a + 7)
    w(f"  - {{circle: [{c[0]}, {c[1]}, {r}], top: 150, wall: 30, top_relief: 6, relief: 40, biome: {b}, tier: 3}}")
w("")
w("# Centrepiece 2, the Great Gorge: a canyon slicing the southern jungle escarpment open from")
w("# the high plateau's foot to the lowland, with BoP Canyon walls and a BoP Lush River floor.")
w("canyons:")
gorge = [pt(R3(90) + 250 + (R2(92) - R3(90) - 500) * i / 14, 91 + 2.6 * math.sin(i * 0.75)) for i in range(15)]   # a smooth winding line
w(f"  - {{points: {line(gorge)}, width: 900, depth: 46, meander: 0, wall_biome: 71, floor_biome: 195, tier: 2}}")
w("")
w("regions:")
w("  # T4 summit: alpine rim round the frozen sky lake")
w(f"  - {{tier: 4, biomes: [[60, 3], [89, 2], [192, 1]], patch: 700, polygon: {line(ring(R4, 4, 1.0, 120))}}}")
# T3 high plateau quadrants
t3 = [
    (212, 302, "[[89, 3], [247, 2], [61, 1]]", "north: BoP Glacier, Tundra, Arctic"),
    (302, 38, "[[251, 2], [78, 2], [254, 1]]", "east: BoP Wasteland, Dead Forest, Xeric Shrubland"),
    (38, 125, "[[195, 3], [187, 2], [185, 1]]", "south: cloud forest - BoP Rainforest, Ominous Woods, Mystic Grove"),
    (125, 212, "[[77, 3], [184, 2], [60, 1]]", "west: BoP Crag, Mountain, Alps"),
]
w("  # T3 high plateau, by climate")
for a0, a1, mix, note in t3:
    w(f"  - {{tier: 3, biomes: {mix}, patch: 900, lakes: [5, 100, 320], polygon: {line(wedge(R3, None, a0, a1, outer_pad=-250))}}}   # {note}")
t2 = [
    (236, 322, "[[74, 3], [86, 2], [59, 1]]", "north: BoP Coniferous Forest, Frost Forest, Alps Forest"),
    (322, 55, "[[37, 3], [39, 2], [190, 2], [71, 1]]", "east: desert mesas - Mesa, Mesa Plateau, BoP Outback, Canyon"),
    (55, 145, "[[245, 3], [195, 2], [62, 1], [21, 1]]", "south: jungle escarpment - BoP Tropical Rainforest, Rainforest, Bamboo, Jungle"),
    (145, 236, "[[142, 2], [183, 2], [141, 1], [80, 1]]", "west: BoP Highland, Moor, Heathland, Deciduous"),
]
w("  # T2 middle plateau, by climate")
for a0, a1, mix, note in t2:
    lk = "[3, 80, 260]" if a0 == 322 else "[9, 100, 380]"
    w(f"  - {{tier: 2, biomes: {mix}, patch: 1100, lakes: {lk}, polygon: {line(wedge(R2, R3, a0, a1, outer_pad=-250, inner_pad=-250))}}}   # {note}")
w("  # Islands")
w("  - {tier: 3, biome: 250, base: 75, relief: 90, circle: [14300, -9800, 1000]}")
w("  - {tier: 2, biome: 14, base: 68, relief: 30, circle: [-14100, -10600, 900]}")
w("  - {tier: 1, biome: 224, base: 66, relief: 15, circle: [10400, 14200, 1700]}")
w("  # Seas by climate, reefs and kelp on the shelf, the atoll's lagoon")
w("  - {biome: 211, sea: true, polygon: [[-16384, -16384], [16384, -16384], [16384, -5500], [-16384, -5500]]}")
w("  - {biome: 210, sea: true, polygon: [[-16384, -16384], [16384, -16384], [16384, -13600], [-16384, -13600]]}")
w("  - {biome: 212, sea: true, polygon: [[-16384, -5500], [16384, -5500], [16384, 4500], [-16384, 4500]]}")
w("  - {biome: 213, sea: true, polygon: [[-16384, 4500], [16384, 4500], [16384, 16384], [-16384, 16384]]}")
w("  - {biome: 75, sea: true, shallow: true, polygon: [[-16384, 6000], [16384, 6000], [16384, 16384], [-16384, 16384]]}")
w("  - {biome: 144, sea: true, shallow: true, polygon: [[-16384, -8000], [-9000, -8000], [-9000, 6000], [-16384, 6000]]}")
w("  - {biome: 75, sea: true, circle: [10400, 14200, 850]}")
t1 = [
    (225, 315, "[[239, 3], [66, 2], [247, 1]]", "north: BoP Snowy Coniferous Forest, Boreal Forest, Tundra", "[12, 120, 450]"),
    (315, 45, "[[35, 2], [242, 2], [70, 1], [254, 1]]", "east: Savanna, BoP Steppe, Brushland, Xeric Shrubland", "[4, 100, 300]"),
    (45, 135, "[[246, 2], [153, 2], [245, 1]]", "south: BoP Tropics, Mangrove, Tropical Rainforest", "[6, 80, 260]"),
    (135, 225, "[[196, 3], [243, 2], [73, 1], [154, 1]]", "west: BoP Redwood Forest, Temperate Rainforest, Cherry Blossom Grove, Maple Woods", "[6, 100, 320]"),
]
w("  # T1 coastal lowlands, by climate")
for a0, a1, mix, note, lk in t1:
    w(f"  - {{tier: 1, biomes: {mix}, base: 70, relief: 45, patch: 1300, lakes: {lk}, polygon: {line(wedge(R0, R2, a0, a1, outer_pad=1600, inner_pad=-250))}}}   # {note}")
w("")
w("ponds:")
w(f"  - {{at: [{CX}, {CZ}], r: 1050, depth: 14, biome: 61}}   # the frozen sky lake on the summit (BoP Arctic)")
w("")
w("ridges:")
w("  # The summit's crown of peaks around the sky lake")
w(f"  - {{arc: [{CX}, {CZ}, 1500, 200, 330], height: 232, width: 700, relief: 200, biome: 60, biome_above: 0.5}}")
w(f"  - {{arc: [{CX}, {CZ}, 1500, 20, 150], height: 226, width: 650, relief: 200, biome: 60, biome_above: 0.5}}")
w("  # Coastal ranges on the north face")
w(f"  - {{points: {line([pt(R0(245) - 1500, 245), pt(R0(270) - 1300, 270), pt(R0(295) - 1500, 295)])}, height: 140, width: 1200, relief: 200, biome: 60, biome_above: 0.6}}")
w("")
w("# Rivers rise on the plateaus and cut gorges down through the escarpments to the sea.")
w("rivers:")
w(f"  - {{points: {line(gorge + [pt(R2(95) + 1500, 97), pt(R0(98) + 900, 98)])}, width: 40, meander: 0, biome: 150}}   # river along the gorge floor, out to sea")
mains = [  # angle, width, biome, tributary offsets (deg)
    (200, 48, None, (-14, 12)),
    (150, 48, None, (-12, 10)),
    (112, 64, 150, (-14, 10, 22)),
    (60, 44, None, (-10, 12)),
    (20, 32, 82, (12,)),
    (330, 40, None, (-12,)),
    (275, 44, 11, (-14, 14)),
]
for a, wd, bio, tribs in mains:
    pts = [pt(R3(a) + 400, a), pt(R2(a) - 1200, a + 3), pt(R2(a) + 600, a - 2), pt(R0(a) + 900, a + 1)]
    extra = f", biome: {bio}" if bio else ""
    extra += ", dry: true" if bio == 82 else ""
    w(f"  - {{points: {line(pts)}, width: {wd}, meander: 260{extra}}}")
    for d in tribs:
        join = pts[2] if abs(d) < 13 else pts[1]
        tp = [pt(R2(a + d) - 600, a + d), pt(R2(a + d) + 900, a + d * 0.6), join]
        w(f"  - {{points: {line(tp)}, width: {max(20, wd // 2)}, meander: 180{extra}}}")
w("")
w("points:")
for a, tier in [(173, 1), (133, 1), (100, 1), (58, 1), (12, 1), (270, 2), (322, 2)]:
    r = R0(a) - 700
    w(f"  - {{kind: spawn, tier: {tier}, x: {pt(r, a)[0]}, z: {pt(r, a)[1]}}}")
