"""Generate option E (stepped highlands) spec for tools/world/plan.py.
Nested escarpments follow radius functions R(theta) with harmonics, so cliffs wind with
bays and spurs; climate quadrants are wedges between the same functions."""
import math, sys

OUT = sys.argv[1]
CX, CZ = 0, -600  # the summit sits a little north, leaving room for the southern jungle escarpment


def rfun(base, harmonics):
    def r(deg):
        t = math.radians(deg)
        return base + sum(a * math.cos(k * t + p) for k, a, p in harmonics)
    return r


R0 = rfun(12600, [(2, 700, 0.4), (3, 900, 1.9), (5, 500, 0.7), (7, 350, 2.8), (11, 220, 1.1)])   # coast
R2 = rfun(8300, [(2, 600, 1.2), (3, 700, 0.3), (5, 650, 2.2), (8, 420, 0.9), (13, 260, 2.5)])    # first escarpment
R3 = rfun(4900, [(2, 400, 2.6), (3, 500, 1.0), (6, 420, 0.2), (9, 300, 1.7), (14, 160, 0.6)])     # second escarpment
R4 = rfun(2000, [(3, 260, 0.9), (5, 180, 2.1), (8, 110, 0.3)])                                     # summit


def pt(r, deg):
    t = math.radians(deg)
    return [round(CX + r * math.cos(t)), round(CZ + r * math.sin(t))]


def ring(rf, step=3, scale=1.0, d=0.0):
    return [pt(rf(a) * scale + d, a) for a in range(0, 360, step)]


def side(a, rin, rout, steps=14):
    """A wedge border from rin to rout at nominal angle a, wandering by up to ~16 degrees,
    so climate borders are not straight spokes. Depends only on a, so neighbours share it."""
    out = []
    for i in range(steps + 1):
        r = rin + (rout - rin) * i / steps
        da = 11 * math.sin(r / 1700 + a * 0.13) + 5 * math.sin(r / 560 + a * 0.71)
        out.append(pt(r, a + da))
    return out


def wedge(outer, inner, a0, a1, step=3, outer_pad=0.0, inner_pad=0.0):
    if a1 < a0:
        a1 += 360
    n = max(1, int((a1 - a0) / step))
    angs = [a0 + (a1 - a0) * i / n for i in range(n + 1)]
    rin0 = (inner(a0 % 360) + inner_pad) if inner else 0
    rin1 = (inner(a1 % 360) + inner_pad) if inner else 0
    pts = side(a0 % 360, rin0, outer(a0 % 360) + outer_pad)
    pts += [pt(outer(a % 360) + outer_pad, a % 360) for a in angs[1:-1]]
    pts += list(reversed(side(a1 % 360, rin1, outer(a1 % 360) + outer_pad)))
    if inner is not None:
        pts += [pt(inner(a % 360) + inner_pad, a % 360) for a in reversed(angs[1:-1])]
    return pts


def flow(a, r):
    return f"[{pt(r, a)[0]}, {pt(r, a)[1]}]"


def line(points):
    return "[" + ", ".join(f"[{x}, {z}]" for x, z in points) + "]"


L = []
