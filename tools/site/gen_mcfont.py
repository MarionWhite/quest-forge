#!/usr/bin/env python3
"""Bake site/lucky/tex/font/ascii.png (the 1.7.10 default font sheet) into site/lucky/mcfont.js.

    python3 -I tools/site/gen_mcfont.py

The sheet is 16x16 cells of 8x8 pixels. FontRenderer.readFontTexture measures each glyph as the
rightmost non-empty column + 2 (a space is 4), which is copied here. The page cannot wait for an
image to decode when it paints a sign, so the glyph bits ship as a hex string instead.
"""
import os, struct, sys, zlib

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(REPO, "site/lucky/tex/font/ascii.png")
OUT = os.path.join(REPO, "site/lucky/mcfont.js")


def read_png(path):
    d = open(path, "rb").read()
    p, idat, hdr, pal, trns = 8, b"", None, None, None
    while p < len(d):
        n, = struct.unpack(">I", d[p:p + 4]); t = d[p + 4:p + 8]; c = d[p + 8:p + 8 + n]; p += 12 + n
        if t == b"IHDR": hdr = struct.unpack(">IIBBBBB", c)
        elif t == b"PLTE": pal = c
        elif t == b"tRNS": trns = c
        elif t == b"IDAT": idat += c
    w, h, bd, ct, _, _, il = hdr
    assert il == 0 and bd == 8, "unsupported PNG"
    ch = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ct]
    raw = zlib.decompress(idat); stride = w * ch; rows = []; prev = bytearray(stride); q = 0
    for _y in range(h):
        f = raw[q]; line = bytearray(raw[q + 1:q + 1 + stride]); q += 1 + stride
        for i in range(stride):
            a = line[i - ch] if i >= ch else 0; b = prev[i]; c2 = prev[i - ch] if i >= ch else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c2), abs(a - c2), abs(a + b - 2 * c2)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else (b if pb <= pc else c2))) & 255
        rows.append(line); prev = line

    def alpha(x, y):
        l = rows[y]
        if ct == 6: return l[x * 4 + 3]
        if ct == 4: return l[x * 2 + 1]
        if ct == 3: return trns[l[x]] if trns and l[x] < len(trns) else 255
        return 255 if l[x] else 0
    return w, h, alpha


def main():
    w, h, alpha = read_png(SRC)
    assert w == h and w % 16 == 0, (w, h)
    cell = w // 16
    scale = cell // 8
    bits, widths = [], []
    for k in range(256):
        cx, cy = (k % 16) * cell, (k // 16) * cell
        rows = []
        for r in range(8):
            v = 0
            for c in range(8):
                on = any(alpha(cx + c * scale + dx, cy + r * scale + dy) > 0 for dx in range(scale) for dy in range(scale))
                v = (v << 1) | (1 if on else 0)
            rows.append(v)
        j = 7
        while j >= 0:
            if any(rows[r] >> (7 - j) & 1 for r in range(8)):
                break
            j -= 1
        if k == 32:
            j = 2
        widths.append(j + 2)
        bits.append("".join("%02x" % v for v in rows))
    js = ("// Generated by tools/site/gen_mcfont.py from tex/font/ascii.png. Do not edit.\n"
          "// GLYPHS: 256 glyphs x 8 rows x 8 bits, hex. WIDTHS: FontRenderer advance per glyph.\n"
          "export const GLYPHS = '" + "".join(bits) + "';\n"
          "export const WIDTHS = [" + ",".join(map(str, widths)) + "];\n"
          "const ROWS = []; for (let k = 0; k < 256; k++) { const r = []; for (let i = 0; i < 8; i++) r.push(parseInt(GLYPHS.substr(k * 16 + i * 2, 2), 16)); ROWS.push(r); }\n"
          "export function mcTextWidth(s) { let w = 0; for (const ch of String(s)) w += WIDTHS[ch.charCodeAt(0) & 255]; return w; }\n"
          "// Paint `s` with its top-left at (x, y) on a canvas context, one font pixel = `px` canvas pixels.\n"
          "export function drawMcText(g, s, x, y, color = '#000', px = 1) {\n"
          "  g.fillStyle = color; let cx = x;\n"
          "  for (const ch of String(s)) {\n"
          "    const code = ch.charCodeAt(0) & 255, rows = ROWS[code];\n"
          "    for (let r = 0; r < 8; r++) for (let c = 0; c < 8; c++) if (rows[r] >> (7 - c) & 1) g.fillRect(Math.round(cx + c * px), Math.round(y + r * px), px, px);\n"
          "    cx += WIDTHS[code] * px;\n"
          "  }\n"
          "}\n")
    open(OUT, "w", encoding="utf-8").write(js)
    print("wrote", OUT, len(js), "bytes; width of 'A' =", widths[65], "space =", widths[32])


if __name__ == "__main__":
    main()
